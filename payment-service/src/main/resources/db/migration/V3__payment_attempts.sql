ALTER TABLE payment_details RENAME TO payments;
CREATE TABLE payment_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_id BIGINT NOT NULL REFERENCES payments(id),
 transaction_reference VARCHAR(100) NOT NULL UNIQUE,
 gateway_provider VARCHAR(50) NOT NULL DEFAULT 'VNPAY',
 gateway_transaction_no VARCHAR(100),
 amount BIGINT NOT NULL CHECK (amount > 0),
 transaction_status VARCHAR(20) NOT NULL,
 response_code VARCHAR(50),
 payment_log TEXT,
 payment_url TEXT,
 idempotency_key VARCHAR(100),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(payment_id,idempotency_key)
);
CREATE UNIQUE INDEX uk_gateway_charge ON payment_transactions(gateway_provider,gateway_transaction_no) WHERE gateway_transaction_no IS NOT NULL;
ALTER TABLE payments ADD COLUMN winning_transaction_id BIGINT REFERENCES payment_transactions(id);
ALTER TABLE payments ADD COLUMN review_required BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE payments ADD COLUMN review_reason VARCHAR(255);
